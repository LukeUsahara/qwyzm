/**
 * Official catalog for Phase 6.5.
 * 前フリ（知られていない情報）→ 後限定（有名な情報）→ 「〜でしょう？」
 */
function id(n: number): string {
  return `c0a80100-0000-4000-8000-${String(n).padStart(12, "0")}`;
}

function q(
  n: number,
  body: string,
  primary: NamedAnswer,
  genreIds: string[],
  extra: { alternates?: NamedAnswer[]; closeInputs?: string[] } = {},
): QuestionCatalogItem {
  return {
    id: id(n),
    body,
    primary,
    alternates: extra.alternates ?? [],
    closeInputs: extra.closeInputs ?? [],
    genreIds,
  };
}

