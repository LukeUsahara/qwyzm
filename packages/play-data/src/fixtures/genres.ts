import type { Genre, GenreKind } from "@qwyzm/shared";

function gid(n: number): string {
  return `c0a80200-0000-4000-8000-${String(n).padStart(12, "0")}`;
}

function g(
  n: number,
  slug: string,
  name: string,
  parent: number | null,
  sortOrder: number,
  kind: GenreKind = "main",
): Genre {
  return {
    id: gid(n),
    parentId: parent === null ? null : gid(parent),
    slug,
    name,
    sortOrder,
    kind,
  };
}

